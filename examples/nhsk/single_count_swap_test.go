func TestSwapSingleCardsMatchesLegacySeatOrder(t *testing.T) {
	deck := []byte{
		0x03, 0x04, 0x05, 0x06, 0x07, 0x13, 0x23, 0x33, 0x08, 0x18, 0x28, 0x38, 0x09,
		0x19, 0x29, 0x39, 0x0a, 0x1a, 0x2a, 0x3a, 0x0b, 0x1b, 0x2b, 0x3b, 0x0c, 0x1c,
		0x0d, 0x1d, 0x2d, 0x3d, 0x01, 0x11, 0x21, 0x31, 0x02, 0x12, 0x22, 0x32, 0x03,
		0x04, 0x05, 0x06, 0x07, 0x17, 0x27, 0x37, 0x08, 0x18, 0x28, 0x38, 0x09, 0x19,
		0x29, 0x39, 0x0a, 0x1a, 0x2a, 0x3a, 0x0b, 0x1b, 0x2b, 0x3b, 0x0c, 0x1c, 0x2c,
		0x3c, 0x0d, 0x1d, 0x2d, 0x3d, 0x01, 0x11, 0x21, 0x31, 0x02, 0x12, 0x22, 0x32,
		0x05, 0x15, 0x25, 0x35, 0x06, 0x16, 0x26, 0x36, 0x07, 0x17, 0x27, 0x37, 0x08,
		0x18, 0x28, 0x38, 0x09, 0x19, 0x29, 0x39, 0x0a, 0x1a, 0x2a, 0x3a,
	}
	want := append([]byte(nil), deck...)
	copy(want[0:26], []byte{
		0x03, 0x03, 0x05, 0x06, 0x07, 0x13, 0x23, 0x33, 0x08, 0x18, 0x28, 0x38, 0x09,
		0x19, 0x29, 0x39, 0x0a, 0x1a, 0x2a, 0x3a, 0x0b, 0x1b, 0x2b, 0x3b, 0x0c, 0x1c,
	})
	copy(want[26:52], []byte{
		0x0d, 0x1d, 0x2d, 0x3d, 0x01, 0x11, 0x21, 0x31, 0x02, 0x12, 0x22, 0x32, 0x04,
		0x04, 0x05, 0x06, 0x07, 0x17, 0x27, 0x37, 0x08, 0x18, 0x28, 0x38, 0x09, 0x19,
	})
	if !reflect.DeepEqual(want[52:], deck[52:]) {
		t.Fatal("test fixture for legacy swap was changed")
	}
	swapSingleCards(deck, 4, 26, 3)
	if !reflect.DeepEqual(deck, want) {
		t.Fatalf("swap result = %x, want %x", deck, want)
	}
}

func TestSwapSingleCardsDisabledForNonPositiveThreshold(t *testing.T) {
	deck := []byte{0x01, 0x02, 0x13, 0x04, 0x11, 0x12, 0x23, 0x24}
	want := append([]byte(nil), deck...)
	swapSingleCards(deck, 2, 4, 0)
	if !reflect.DeepEqual(deck, want) {
		t.Fatalf("disabled swap changed deck = %x, want %x", deck, want)
	}
}

func TestBattleSingleCountGolden(t *testing.T) {
	battle := newPlayingBattleWithSeed(t, 100, 1)
	want := [][]byte{
		{0x29, 0x23, 0x1b, 0x16, 0x39, 0x25, 0x15, 0x16, 0x08, 0x2b, 0x1d, 0x3a, 0x35, 0x2a, 0x17, 0x1c, 0x3a, 0x23, 0x0a, 0x13, 0x07, 0x3c, 0x34, 0x36, 0x14, 0x37},
		{0x27, 0x0d, 0x21, 0x13, 0x09, 0x2c, 0x32, 0x31, 0x2d, 0x22, 0x19, 0x11, 0x1a, 0x3d, 0x22, 0x21, 0x02, 0x33, 0x11, 0x38, 0x1c, 0x19, 0x2d, 0x36, 0x28, 0x37},
		{0x1a, 0x3d, 0x24, 0x04, 0x03, 0x17, 0x05, 0x02, 0x3c, 0x28, 0x2b, 0x09, 0x2c, 0x0a, 0x08, 0x26, 0x0b, 0x1b, 0x39, 0x07, 0x0d, 0x27, 0x0b, 0x04, 0x3b, 0x24},
		{0x25, 0x06, 0x34, 0x18, 0x3b, 0x1d, 0x12, 0x26, 0x2a, 0x01, 0x0c, 0x29, 0x18, 0x32, 0x38, 0x05, 0x33, 0x06, 0x15, 0x35, 0x0c, 0x03, 0x31, 0x01, 0x12, 0x14},
	}
	counts := make(map[byte]int, 52)
	for seat, player := range battle.bySeat {
		if !reflect.DeepEqual(battle.hands[player], want[seat]) {
			t.Fatalf("seed=1 seat=%d cards=%x, want %x", seat, battle.hands[player], want[seat])
		}
		if got := countSingleCards(battle.hands[player]); got > 4 {
			t.Fatalf("seed=1 seat=%d singles=%d, want <=4", seat, got)
		}
		for _, card := range battle.hands[player] {
			counts[card]++
		}
	}
	if len(counts) != 52 {
		t.Fatalf("deal distinct card count = %d, want 52", len(counts))
	}
	for card, count := range counts {
		if count != 2 {
			t.Fatalf("card %x count = %d, want 2", card, count)
		}
	}
}

func countSingleCards(cards []byte) int {
	return len(singleCards(cards))
}
